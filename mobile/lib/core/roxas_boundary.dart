bool insideRoxas(double? lat, double? lng) {
  if (lat == null || lng == null) return false;
  var inside = false;
  for (var i = 1; i < roxasOutline.length; i++) {
    final a = roxasOutline[i - 1];
    final b = roxasOutline[i];
    if ((a.latitude > lat) != (b.latitude > lat) &&
        lng < (b.longitude - a.longitude) * (lat - a.latitude) /
                (b.latitude - a.latitude) + a.longitude) {
      inside = !inside;
    }
  }
  return inside;
}
